export function quarterContaining(surah: number, ayah: number): Quarter | null {
  if (!Number.isInteger(surah) || surah < 1 || surah > 114) return null;
  const count = SURAH_AYAH_COUNTS[surah - 1];
  if (!Number.isInteger(ayah) || ayah < 1 || ayah > count) return null;
  for (const qu of QUARTERS) {
    if (
      (surah > qu.startSurah || (surah === qu.startSurah && ayah >= qu.startAyah)) &&
      (surah < qu.endSurah || (surah === qu.endSurah && ayah <= qu.endAyah))
    ) return qu;
  }
  return null;
}

export function quarterAyahs(qu: Quarter): { surah: number; ayah: number }[] {
  const out: { surah: number; ayah: number }[] = [];
  let s = qu.startSurah;
  let a = qu.startAyah;
  for (;;) {
    out.push({ surah: s, ayah: a });
    if (s === qu.endSurah && a === qu.endAyah) break;
    const count = SURAH_AYAH_COUNTS[s - 1];
    if (a >= count) { s += 1; a = 1; } else { a += 1; }
  }
  return out;
}

export function nextQuarter(qu: Quarter): Quarter | null {
  return QUARTERS.find((x) => x.q === qu.q + 1) ?? null;
}
