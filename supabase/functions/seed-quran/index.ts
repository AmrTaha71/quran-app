Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { status: 200, headers: corsHeaders });
  }

  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const supabase = createClient(supabaseUrl, serviceRoleKey);

    // Check if already seeded
    const { count } = await supabase
      .from("quran_verses")
      .select("*", { count: "exact", head: true });

    if (count && count >= 6236) {
      return new Response(
        JSON.stringify({ message: "Already seeded", count }),
        { headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    // Fetch Quran data
    const resp = await fetch(
      "https://raw.githubusercontent.com/fawazahmed0/quran-api/1/editions/ara-quranindopak.json"
    );
    const data = await resp.json();
    const verses = data.quran;

    const verseObjects = verses.map((v: { chapter: number; verse: number; text: string }) => ({
      surah_no: v.chapter,
      surah_name: surahNames[v.chapter] || "",
      ayah_no: v.verse,
      ayah_text: v.text,
      has_links: false,
      links_count: 0,
      is_protected: false,
    }));

    let totalInserted = 0;
    const batchSize = 500;
    for (let i = 0; i < verseObjects.length; i += batchSize) {
      const batch = verseObjects.slice(i, i + batchSize);
      const { error } = await supabase
        .from("quran_verses")
        .upsert(batch, { onConflict: "surah_no,ayah_no", ignoreDuplicates: true });
      if (error) throw error;
      totalInserted += batch.length;
    }

    return new Response(
      JSON.stringify({ message: "Seeded successfully", count: totalInserted }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  } catch (err) {
    return new Response(
      JSON.stringify({ error: err.message }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
